font="/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
bold="/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
def ft(s,b=False):return ImageFont.truetype(bold if b else font,s)
def shade(im,start,end,opacity):
 im=im.convert("RGBA");over=Image.new("RGBA",im.size,(0,0,0,0));d=ImageDraw.Draw(over)
 for y in range(start,end):
  v=(y-start)/max(1,end-start)
  d.line((0,y,im.width,y),fill=(0,0,0,int(opacity*v*v)))
 return Image.alpha_composite(im,over)
def put_logo(im,x,y,sz):
 l=ImageOps.contain(logo,(sz,sz));im.alpha_composite(l,(x,y))
